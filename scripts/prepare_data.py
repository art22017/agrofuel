"""Build a reproducible local price snapshot from saved public search extracts.
No imputation, interpolation, or generated observations.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
def parse(path):
    text = path.read_text(encoding='utf-8')
    result = {}
    for line in text.splitlines():
        cols = [x.strip() for x in line.split('|')]
        if len(cols) != 6 or not all(re.fullmatch(r'\d+,\d+|\.\.\.', x) for x in cols[1:]):
            continue
        name = cols[0].replace('*', '').strip()
        if 'федеральный' in name or 'топливо' in name or name.startswith(('авт. ', 'Югры ')):
            continue
        name = name.replace('в том числе: ', '')
        if name == 'Архангельская область':
            # The parent aggregate overlaps with Nenets; use the non-overlapping
            # remainder row, which is present immediately below in the source.
            continue
        if name == 'Ненецкого авт. округа)': name = 'Архангельская область'
        result[name] = {k: None if v == '...' else float(v.replace(',', '.')) for k,v in zip(['gas','ai92','ai95','ai98','diesel'],cols[1:])}
    return result

